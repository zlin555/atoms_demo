def extract_json_object(text: str) -> dict | None:
    """Parse strict JSON first, then recover JSON wrapped in markdown fences."""
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    fenced = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, flags=re.DOTALL)
    if fenced:
        try:
            return json.loads(fenced.group(1))
        except json.JSONDecodeError:
            return None

    start = text.find("{")
    end = text.rfind("}")
    if start >= 0 and end > start:
        try:
            return json.loads(text[start : end + 1])
        except json.JSONDecodeError:
            return None
    return None


def normalize_cards(value: object, fallback_cards: list[dict]) -> list[dict]:
    if not isinstance(value, list):
        return fallback_cards
    cards = []
    for item in value[:6]:
        if not isinstance(item, dict):
            continue
        title = str(item.get("title", "")).strip()
        copy = str(item.get("copy", "")).strip()
        if title and copy:
            cards.append({"title": title[:48], "copy": copy[:160]})
    return cards or fallback_cards


def normalize_buttons(value: object, fallback_buttons: list[str]) -> list[str]:
    if not isinstance(value, list):
        return fallback_buttons
    buttons = [str(item).strip()[:32] for item in value[:3] if str(item).strip()]
    return buttons or fallback_buttons


def normalize_list(value: object, fallback: list[str], limit: int = 6, item_limit: int = 48) -> list[str]:
    if not isinstance(value, list):
        return fallback
    items = [str(item).strip()[:item_limit] for item in value[:limit] if str(item).strip()]
    return items or fallback


def normalize_sections(value: object) -> list[dict]:
    if not isinstance(value, list):
        return []
    sections = []
    for item in value[:5]:
        if not isinstance(item, dict):
            continue
        title = str(item.get("title", "")).strip()
        copy = str(item.get("copy", "")).strip()
        bullets = normalize_list(item.get("bullets"), [], limit=4, item_limit=80)
        if title and copy:
            sections.append({"title": title[:56], "copy": copy[:220], "bullets": bullets})
    return sections


def apply_ai_result(build: dict, ai_result: dict | None, fallback_template: dict) -> dict:
    build["ai"] = {
        "enabled": AI_STATUS["enabled"],
        "used": bool(ai_result),
        "model": AI_MODEL if AI_STATUS["enabled"] else "",
        "lastError": AI_STATUS["last_error"],
    }
    if not ai_result:
        reason = AI_STATUS["last_error"] or "AI_API_BASE_URL or AI_API_KEY is not configured"
        build["logs"].append(f"[ai] provider unavailable; used deterministic fallback; reason={reason}")
        return build

    preview = ai_result.get("preview") if isinstance(ai_result.get("preview"), dict) else {}
    message = str(ai_result.get("message", "")).strip()
    code = str(ai_result.get("code", "")).strip()
    logs = ai_result.get("logs") if isinstance(ai_result.get("logs"), list) else []

    build["message"] = message[:500] or build["message"]
    build["preview"]["title"] = str(preview.get("title", build["preview"]["title"])).strip()[:96]
    build["preview"]["copy"] = str(preview.get("copy", build["preview"]["copy"])).strip()[:360]
    build["preview"]["buttons"] = normalize_buttons(preview.get("buttons"), fallback_template["buttons"])
    build["preview"]["cards"] = normalize_cards(preview.get("cards"), fallback_template["cards"])
    build["preview"]["theme"] = str(preview.get("theme", "light")).strip()[:24] or "light"
    build["preview"]["nav"] = normalize_list(preview.get("nav"), ["Home", "Dashboard", "Settings"], limit=5)
    build["preview"]["metrics"] = normalize_cards(preview.get("metrics"), [])
    build["preview"]["sections"] = normalize_sections(preview.get("sections"))
    if code:
        build["code"] = code[:9000]

    clean_logs = [str(item).strip()[:240] for item in logs if str(item).strip()]
    build["logs"].extend([f"[ai] {item}" for item in clean_logs[:8]])
    build["logs"].append("[ai] model response applied to preview and code")
    return build


def chat_completions_endpoint() -> str:
    if AI_API_BASE_URL.endswith("/chat/completions"):
        return AI_API_BASE_URL
    return f"{AI_API_BASE_URL}/chat/completions"


def ai_system_prompt() -> str:
    return """
You are the backend agent runtime for an Atoms-style app builder.
The user describes an app. Generate a realistic interactive app preview and React code.

Return only valid JSON with this exact shape:
{
  "message": "short Chinese assistant response",
  "preview": {
    "title": "preview hero title",
    "copy": "Chinese summary based on the user request",
    "theme": "light | dark | minimal | playful | enterprise",
    "nav": ["nav item"],
    "buttons": ["primary action", "secondary action"],
    "metrics": [
      {"title": "metric label", "copy": "metric value or short status"}
    ],
    "cards": [
      {"title": "feature name", "copy": "short Chinese feature description"}
    ],
    "sections": [
      {"title": "page section", "copy": "what this section contains", "bullets": ["detail"]}
    ]
  },
  "code": "React JSX code string for the generated app",
  "logs": ["planner log", "coder log", "verifier log"]
}

Rules:
- Keep the generated app concrete and useful.
- Make the preview visibly different for different user requests, not just rewritten text.
- Use nav, metrics, cards, and sections to describe the generated page structure.
- Do not include markdown fences.
- The code should be displayable as source in a demo. It does not need external packages.
- Include Planner, Coder, and Verifier behavior in logs.
""".strip()


async def call_ai_provider(prompt: str, template: dict, mode: BuildMode, history: list[dict[str, str]]) -> dict | None:
    if not AI_API_BASE_URL or not AI_API_KEY:
        AI_STATUS["enabled"] = False
        AI_STATUS["last_ok"] = False
        AI_STATUS["last_error"] = "AI_API_BASE_URL or AI_API_KEY is missing"
        return None

    AI_STATUS["enabled"] = True
    AI_STATUS["last_error"] = ""
    endpoint = chat_completions_endpoint()
    compact_history = [
        {"role": item.get("role", "user"), "content": item.get("content", "")[:800]}
        for item in history[-8:]
        if item.get("content")
    ]
    user_payload = {
        "prompt": prompt,
        "mode": mode,
        "starterTemplate": {
            "name": template["name"],
            "summary": template["summary"],
            "currentCards": template["cards"],
        },
    }

    body = {
        "model": AI_MODEL,
        "temperature": 0.45 if mode == "fast" else 0.7,
        "response_format": {"type": "json_object"},
        "messages": [
            {"role": "system", "content": ai_system_prompt()},
            *compact_history,
            {"role": "user", "content": json.dumps(user_payload, ensure_ascii=False)},
        ],
    }

    try:
        async with httpx.AsyncClient(timeout=AI_TIMEOUT_SECONDS) as client:
            response = await client.post(
                endpoint,
                headers={"Authorization": f"Bearer {AI_API_KEY}", "Content-Type": "application/json"},
                json=body,
            )
            response.raise_for_status()
            payload = response.json()
    except httpx.HTTPStatusError as exc:
        detail = exc.response.text[:500] if exc.response is not None else ""
        AI_STATUS["last_ok"] = False
        AI_STATUS["last_error"] = f"HTTP {exc.response.status_code if exc.response else 'unknown'} from AI provider: {detail}"
        return None
    except Exception as exc:
        AI_STATUS["last_ok"] = False
        AI_STATUS["last_error"] = f"{type(exc).__name__}: {str(exc)[:500]}"
        return None

    content = (
        payload.get("choices", [{}])[0]
        .get("message", {})
        .get("content", "")
    )
    if not content:
        AI_STATUS["last_ok"] = False
        AI_STATUS["last_error"] = "AI provider returned an empty message"
        return None
    parsed = extract_json_object(content)
    if not parsed:
        AI_STATUS["last_ok"] = False
        AI_STATUS["last_error"] = "AI provider response was not valid JSON"
        return None
    AI_STATUS["last_ok"] = True
    AI_STATUS["last_error"] = ""
    return parsed


async def make_build(
    prompt: str,
    template_id: TemplateId,
    mode: BuildMode,
    source: str = "chat",
    history: list[dict[str, str]] | None = None,
) -> dict:
    resolved_template_id = detect_template(prompt, template_id)
    template = TEMPLATES[resolved_template_id]
    build_id = f"build_{uuid.uuid4().hex[:10]}"
    requirement = summarize_requirement(prompt)
    created = now_iso()
    steps = [
        {
            "id": "planner",
            "agent": "Planner",
            "title": "提取产品范围、页面结构和数据模型",
            "durationMs": 700 if mode == "fast" else 1100,
        },
        {
            "id": "coder",
            "agent": "Coder",
            "title": "生成组件、状态、示例数据和交互事件",
            "durationMs": 900 if mode == "fast" else 1400,
        },
        {
            "id": "verifier",
            "agent": "Verifier",
            "title": "检查响应式布局、空状态、日志和发布流程",
            "durationMs": 650 if mode == "fast" else 1200,
        },
    ]
    preview = {
        "name": template["name"],
        "slug": template["slug"],
        "title": template["title"],
        "copy": f"基于你的需求：{requirement}" if prompt else template["copy"],
        "buttons": template["buttons"],
        "cards": template["cards"],
        "url": f"https://preview.atoms.local/{template['slug']}",
    }
    logs = [
        f"[{created}] [{source}] prompt received",
        f"[planner] selected template={resolved_template_id}, mode={mode}",
        "[coder] generated route, components, state model, preview data",
        "[verifier] responsive pass, contrast pass, empty-state pass",
        f"[artifact] build_id={build_id}",
    ]
    build = {
        "id": build_id,
        "status": "ready",
        "mode": mode,
        "templateId": resolved_template_id,
        "prompt": prompt,
        "createdAt": created,
        "steps": steps,
        "message": "预览已经更新。你可以继续要求我添加页面、改样式、补数据库字段，或直接发布。",
        "preview": preview,
        "code": generated_code(template, prompt or template["copy"], mode),
        "files": [],
        "logs": logs,
    }
    ai_result = await call_ai_provider(prompt, template, mode, history or [])
    build = apply_ai_result(build, ai_result, template)
    build["files"] = generated_files(build_id, template, build["preview"], build["code"], prompt or template["copy"], mode)
    BUILDS[build_id] = build
    return build


app = FastAPI(title="Atoms Agent Builder Demo API", version="1.0.0")

