@app.post("/api/builds")
async def create_build(request: BuildRequest) -> dict:
    build = await make_build(request.prompt, request.template_id, request.mode, history=request.history)
    return {"build": build}


@app.post("/api/builds/rerun")
async def rerun_build(request: RerunRequest) -> dict:
    previous = BUILDS.get(request.build_id)
    if not previous:
        raise HTTPException(status_code=404, detail="Build not found")
    prompt = request.instruction or f"重新运行 {previous['preview']['name']}，保持当前功能但优化视觉层级。"
    build = await make_build(prompt, previous["templateId"], request.mode, source="rerun")
    return {"build": build}


@app.get("/api/builds/{build_id}")
def get_build(build_id: str) -> dict:
    build = BUILDS.get(build_id)
    if not build:
        raise HTTPException(status_code=404, detail="Build not found")
    return {"build": build}


@app.get("/api/builds/{build_id}/export")
def export_build(build_id: str):
    build = BUILDS.get(build_id)
    if not build:
        raise HTTPException(status_code=404, detail="Build not found")

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, mode="w", compression=zipfile.ZIP_DEFLATED) as archive:
        if build.get("files"):
            for file in build["files"]:
                archive.writestr(file["path"], file["content"])
        else:
            archive.writestr("README.md", f"# {build['preview']['name']}\n\nGenerated by Atoms Agent Demo API.\n")
            archive.writestr("frontend/src/App.jsx", build["code"])
            archive.writestr("build.json", json.dumps(build, ensure_ascii=False, indent=2))
        archive.writestr("logs.txt", "\n".join(build["logs"]))
    buffer.seek(0)

    filename = f"{build['preview']['slug']}-{int(time.time())}.zip"
    headers = {"Content-Disposition": f'attachment; filename="{filename}"'}
    return StreamingResponse(buffer, media_type="application/zip", headers=headers)


@app.post("/api/publish")
def publish_build(request: PublishRequest) -> dict:
    build = BUILDS.get(request.build_id)
    if not build:
        raise HTTPException(status_code=404, detail="Build not found")
    published = {
        "buildId": build["id"],
        "status": "published",
        "publishedAt": now_iso(),
        "url": f"https://preview.atoms.local/live/{build['preview']['slug']}",
    }
    PUBLISHED[build["id"]] = published
    return {"publish": published}
